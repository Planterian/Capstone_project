class IViTMobileViTTransformerLayer(nn.Module):
    """
    Drop-in replacement for HuggingFace's `MobileViTTransformerLayer`.

    Structure comparison:
    ┌──────────────────────────────────────────────┐
    │  HF (FP32)                │  I-ViT (INT)     │
    ├──────────────────────────────────────────────┤
    │  layernorm_before (LN)    │  norm1 (IntLN)   │
    │  attention (SA + proj)    │  attn (IViTSA)   │
    │  residual add             │  qact_res1       │
    │  layernorm_after  (LN)    │  norm2 (IntLN)   │
    │  intermediate (fc1+act)   │  mlp  (IViTMlp)  │
    │  output (fc2+drop+resid)  │  qact_res2       │
    └──────────────────────────────────────────────┘

    The forward() signature accepts and returns a *plain tensor* (no
    scaling-factor tuple) so the surrounding MobileViTTransformer loop
    does not need to change.  We create and consume the QuantAct
    context internally.
    """

    def __init__(self, hidden_size: int, intermediate_size: int,
                 num_attention_heads: int,
                 attn_drop: float = 0.0,
                 hidden_drop: float = 0.0,
                 qkv_bias: bool = True,
                 layer_norm_eps: float = 1e-5):
        super().__init__()

        # --- Integer LayerNorms ---
        self.norm1 = IntLayerNorm(hidden_size, eps=layer_norm_eps)
        self.norm2 = IntLayerNorm(hidden_size, eps=layer_norm_eps)

        # --- Entry / exit quantisation ---
        self.qact_input = QuantAct()    # bootstrap scaling factor from raw FP tensor
        self.qact1 = QuantAct()         # after norm1
        self.qact_res1 = QuantAct(16)   # residual-add after attention
        self.qact3 = QuantAct()         # after norm2
        self.qact_res2 = QuantAct(16)   # residual-add after MLP

        # --- Core blocks ---
        self.attn = IViTSelfAttention(
            hidden_size=hidden_size,
            num_attention_heads=num_attention_heads,
            attn_drop=attn_drop,
            qkv_bias=qkv_bias,
        )

        self.mlp = IViTMlp(
            hidden_size=hidden_size,
            intermediate_size=intermediate_size,
            drop=hidden_drop,
        )

    def forward(self, hidden_states: torch.Tensor) -> torch.Tensor:
        """
        Accepts a plain tensor (B*P, N, C) from the HF pipeline,
        runs everything through I-ViT quantised blocks, and returns
        a plain tensor.
        """
        # --- Bootstrap quantisation context ---
        x_1, act_scaling_factor_1 = self.qact_input(hidden_states)

        # --- Pre-norm + Self-Attention ---
        x, act_scaling_factor = self.norm1(x_1, act_scaling_factor_1)
        x, act_scaling_factor = self.qact1(x, act_scaling_factor)
        x, act_scaling_factor = self.attn(x, act_scaling_factor)

        # --- Residual add (attention output + input) ---
        x_2, act_scaling_factor_2 = self.qact_res1(
            x, act_scaling_factor, x_1, act_scaling_factor_1)

        # --- Pre-norm + MLP ---
        x, act_scaling_factor = self.norm2(x_2, act_scaling_factor_2)
        x, act_scaling_factor = self.qact3(x, act_scaling_factor)
        x, act_scaling_factor = self.mlp(x, act_scaling_factor)

        # --- Residual add (MLP output + attention-residual) ---
        x, act_scaling_factor = self.qact_res2(
            x, act_scaling_factor, x_2, act_scaling_factor_2)

        # Strip the quantisation context -> plain tensor for HF pipeline
        return x


