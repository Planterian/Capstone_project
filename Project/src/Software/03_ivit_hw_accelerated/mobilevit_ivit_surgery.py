def find_transformer_layer_paths(model: nn.Module) -> list:
    """
    Walk the model graph and return dotted-path prefixes for every
    `MobileViTTransformerLayer` instance.
    """
    from transformers.models.mobilevit.modeling_mobilevit import (
        MobileViTTransformerLayer,
    )
    paths = []
    for name, module in model.named_modules():
        if isinstance(module, MobileViTTransformerLayer):
            paths.append(name)
    return paths


def _set_module_by_name(model: nn.Module, dotted_name: str, new_module: nn.Module):
    """Utility: set `model.<dotted_name> = new_module` using recursive getattr."""
    parts = dotted_name.split(".")
    parent = model
    for p in parts[:-1]:
        parent = getattr(parent, p)
    setattr(parent, parts[-1], new_module)


def replace_mobilevit_blocks(model: nn.Module,
                             num_attention_heads: int = 4,
                             mlp_ratio: float = 2.0,
                             qkv_bias: bool = True,
                             attn_drop: float = 0.0,
                             hidden_drop: float = 0.0,
                             layer_norm_eps: float = 1e-5) -> nn.Module:
    """
    Traverse `model.named_modules()`, identify every HuggingFace
    `MobileViTTransformerLayer`, and replace it in-place with an
    `IViTMobileViTTransformerLayer` that uses I-ViT integer-only
    primitives.

    Parameters
    ----------
    model : nn.Module
        A HuggingFace `MobileViTForImageClassification` (or any model
        containing `MobileViTTransformerLayer` instances).
    num_attention_heads : int
        Number of attention heads (default 4 for mobilevit-xx-small).
    mlp_ratio : float
        Expansion ratio for the MLP intermediate size (default 2.0).
    qkv_bias : bool
        Whether the QKV projection includes bias (default True).

    Returns
    -------
    model : nn.Module
        The same model object with transformer layers swapped.
    replaced_prefixes : list of str
        Dotted paths of the replaced layers (needed by `transfer_weights`).
    """
    from transformers.models.mobilevit.modeling_mobilevit import (
        MobileViTTransformerLayer,
    )

    # --- Snapshot the original state dict BEFORE any replacement ---
    original_state = copy.deepcopy(model.state_dict())

    replaced_prefixes = []

    for name, module in list(model.named_modules()):
        if not isinstance(module, MobileViTTransformerLayer):
            continue

        # Infer hidden_size from the existing LayerNorm
        hidden_size = module.layernorm_before.normalized_shape[0]
        intermediate_size = int(hidden_size * mlp_ratio)

        # Build the replacement
        new_layer = IViTMobileViTTransformerLayer(
            hidden_size=hidden_size,
            intermediate_size=intermediate_size,
            num_attention_heads=num_attention_heads,
            attn_drop=attn_drop,
            hidden_drop=hidden_drop,
            qkv_bias=qkv_bias,
            layer_norm_eps=layer_norm_eps,
        )

        # Swap it into the model graph
        _set_module_by_name(model, name, new_layer)
        replaced_prefixes.append(name)
        print(f"  [SURGERY] Replaced: {name}  "
              f"(hidden={hidden_size}, inter={intermediate_size})")

    # --- Transfer pre-trained weights ---
    model = transfer_weights(original_state, model, replaced_prefixes)

    return model, replaced_prefixes


