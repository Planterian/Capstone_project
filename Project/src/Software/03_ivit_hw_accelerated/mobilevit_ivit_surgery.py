# 1. Integer-only Self-Attention (replaces MobileViTSelfAttention)
# ===================================================================

class IViTSelfAttention(nn.Module):
    """
    Integer-only self-attention that mirrors HuggingFace's
    `MobileViTSelfAttention` but uses I-ViT primitives.

    HF layout (separate Q / K / V projections, each `hidden_size -> hidden_size`):
        query  = nn.Linear(hidden_size, all_head_size)
        key    = nn.Linear(hidden_size, all_head_size)
        value  = nn.Linear(hidden_size, all_head_size)

    I-ViT layout (fused QKV, `hidden_size -> 3 * hidden_size`):
        qkv = QuantLinear(hidden_size, 3 * hidden_size)

    During weight transfer we *fuse* the three HF weight matrices into
    the single QKV weight matrix expected by I-ViT.
    """

    def __init__(self, hidden_size: int, num_attention_heads: int,
                 attn_drop: float = 0.0, qkv_bias: bool = True):
        super().__init__()
        self.num_attention_heads = num_attention_heads
        self.attention_head_size = hidden_size // num_attention_heads
        self.all_head_size = num_attention_heads * self.attention_head_size
        self.scale = self.attention_head_size ** -0.5

        # ---------- I-ViT quantised layers ----------
        self.qkv = QuantLinear(hidden_size, hidden_size * 3, bias=qkv_bias)
        self.qact1 = QuantAct()            # after QKV projection
        self.qact_attn1 = QuantAct()       # after Q·K^T scaling
        self.int_softmax = IntSoftmax(16)  # Shiftmax (16-bit accumulation)
        self.qact_softmax = QuantAct()     # (kept for future calibration hooks)
        self.qact2 = QuantAct()            # after context reshape
        self.proj = QuantLinear(hidden_size, hidden_size, bias=True)
        self.qact3 = QuantAct(16)          # output quantisation

        self.matmul_1 = QuantMatMul()      # Q · K^T
        self.matmul_2 = QuantMatMul()      # attn · V

        self.attn_drop = nn.Dropout(attn_drop)

    # ---- forward bridges I-ViT tuple protocol ----
    def forward(self, x: torch.Tensor, act_scaling_factor: torch.Tensor):
        B, N, C = x.shape

        # QKV projection (fused)
        x, act_scaling_factor = self.qkv(x, act_scaling_factor)
        x, act_scaling_factor_1 = self.qact1(x, act_scaling_factor)

        qkv = x.reshape(B, N, 3, self.num_attention_heads,
                         C // self.num_attention_heads).permute(2, 0, 3, 1, 4)
        q, k, v = qkv[0], qkv[1], qkv[2]

        # Attention scores  (Q · K^T) / sqrt(d)
        attn, act_scaling_factor = self.matmul_1(
            q, act_scaling_factor_1,
            k.transpose(-2, -1), act_scaling_factor_1)
        attn = attn * self.scale
        act_scaling_factor = act_scaling_factor * self.scale
        attn, act_scaling_factor = self.qact_attn1(attn, act_scaling_factor)

        # Shiftmax (integer softmax)
        attn, act_scaling_factor = self.int_softmax(attn, act_scaling_factor)
        attn = self.attn_drop(attn)

        # Context  (attn · V)
        x, act_scaling_factor = self.matmul_2(
            attn, act_scaling_factor,
            v, act_scaling_factor_1)
        x = x.transpose(1, 2).reshape(B, N, C)

        # Output projection
        x, act_scaling_factor = self.qact2(x, act_scaling_factor)
        x, act_scaling_factor = self.proj(x, act_scaling_factor)
        x, act_scaling_factor = self.qact3(x, act_scaling_factor)

        return x, act_scaling_factor


