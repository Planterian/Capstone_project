def build_weight_map(old_prefix: str, new_prefix: str) -> dict:
    """
    Build the state-dict key mapping from a single HF
    `MobileViTTransformerLayer` to an `IViTMobileViTTransformerLayer`.

    Parameters
    ----------
    old_prefix : str
        The dotted prefix in the *original* model's state_dict that
        points to one MobileViTTransformerLayer, e.g.
        ``"mobilevit.encoder.layer.2.transformer.layer.0"``.
    new_prefix : str
        The corresponding prefix in the *surgered* model (usually
        identical to old_prefix after in-place replacement).

    Returns
    -------
    dict  {old_key: new_key}

    Key Mapping Table
    -----------------
    HF Original Key                          →  I-ViT Replacement Key
    ──────────────────────────────────────────────────────────────────
    # LayerNorms
    layernorm_before.weight                  →  norm1.weight
    layernorm_before.bias                    →  norm1.bias
    layernorm_after.weight                   →  norm2.weight
    layernorm_after.bias                     →  norm2.bias

    # Self-Attention Q/K/V → fused QKV
    #   HF has separate query / key / value  (each hidden_size × hidden_size)
    #   I-ViT fuses them into one            (hidden_size × 3·hidden_size)
    #   → these are handled specially via `fuse_qkv_weights()`, NOT via
    #     simple key rename.  The map below lists them for documentation
    #     purposes; the actual transfer is done programmatically.
    attention.attention.query.weight         →  attn.qkv.weight  (rows 0:H)
    attention.attention.query.bias           →  attn.qkv.bias    (rows 0:H)
    attention.attention.key.weight           →  attn.qkv.weight  (rows H:2H)
    attention.attention.key.bias             →  attn.qkv.bias    (rows H:2H)
    attention.attention.value.weight         →  attn.qkv.weight  (rows 2H:3H)
    attention.attention.value.bias           →  attn.qkv.bias    (rows 2H:3H)

    # Self-Attention output projection
    attention.output.dense.weight            →  attn.proj.weight
    attention.output.dense.bias              →  attn.proj.bias

    # MLP  fc1  (was MobileViTIntermediate.dense)
    intermediate.dense.weight                →  mlp.fc1.weight
    intermediate.dense.bias                  →  mlp.fc1.bias

    # MLP  fc2  (was MobileViTOutput.dense)
    output.dense.weight                      →  mlp.fc2.weight
    output.dense.bias                        →  mlp.fc2.bias
    """

    # Simple 1-to-1 renames (everything except QKV which needs fusing)
    mapping = {
        # LayerNorms
        f"{old_prefix}.layernorm_before.weight": f"{new_prefix}.norm1.weight",
        f"{old_prefix}.layernorm_before.bias":   f"{new_prefix}.norm1.bias",
        f"{old_prefix}.layernorm_after.weight":  f"{new_prefix}.norm2.weight",
        f"{old_prefix}.layernorm_after.bias":    f"{new_prefix}.norm2.bias",

        # Attention output projection
        f"{old_prefix}.attention.output.dense.weight": f"{new_prefix}.attn.proj.weight",
        f"{old_prefix}.attention.output.dense.bias":   f"{new_prefix}.attn.proj.bias",

        # MLP fc1  (Intermediate)
        f"{old_prefix}.intermediate.dense.weight": f"{new_prefix}.mlp.fc1.weight",
        f"{old_prefix}.intermediate.dense.bias":   f"{new_prefix}.mlp.fc1.bias",

        # MLP fc2  (Output)
        f"{old_prefix}.output.dense.weight": f"{new_prefix}.mlp.fc2.weight",
        f"{old_prefix}.output.dense.bias":   f"{new_prefix}.mlp.fc2.bias",
    }
    return mapping


def fuse_qkv_weights(old_state: dict, old_prefix: str,
                     new_state: dict, new_prefix: str):
    """
    Fuse three separate Q / K / V weight matrices from HuggingFace's
    `MobileViTSelfAttention` into the single concatenated QKV matrix
    expected by I-ViT's `QuantLinear(dim, 3*dim)`.

    Layout in the fused tensor (dim=H):
        qkv.weight = [ Q.weight ]   rows  0 : H
                     [ K.weight ]   rows  H : 2H
                     [ V.weight ]   rows 2H : 3H
    Same for bias.
    """
    q_w = old_state[f"{old_prefix}.attention.attention.query.weight"]
    k_w = old_state[f"{old_prefix}.attention.attention.key.weight"]
    v_w = old_state[f"{old_prefix}.attention.attention.value.weight"]

    new_state[f"{new_prefix}.attn.qkv.weight"] = torch.cat([q_w, k_w, v_w], dim=0)

    q_b_key = f"{old_prefix}.attention.attention.query.bias"
    k_b_key = f"{old_prefix}.attention.attention.key.bias"
    v_b_key = f"{old_prefix}.attention.attention.value.bias"

    if q_b_key in old_state:
        q_b = old_state[q_b_key]
        k_b = old_state[k_b_key]
        v_b = old_state[v_b_key]
        new_state[f"{new_prefix}.attn.qkv.bias"] = torch.cat([q_b, k_b, v_b], dim=0)


def transfer_weights(old_model_state: dict,
                     new_model: nn.Module,
                     layer_prefixes: list):
    """
    Transfer ALL pre-trained weights from the original FP32 model to
    the surgered I-ViT model.

    Parameters
    ----------
    old_model_state : dict
        `original_model.state_dict()` (before surgery).
    new_model : nn.Module
        The model **after** block replacement.
    layer_prefixes : list of str
        Dotted prefixes for each MobileViTTransformerLayer that was
        replaced, e.g.:
          ["mobilevit.encoder.layer.2.transformer.layer.0",
           "mobilevit.encoder.layer.2.transformer.layer.1", ...]

    Returns
    -------
    new_model with weights loaded (in-place).
    """
    new_state = new_model.state_dict()

    # ------------------------------------------------------------------
    # Step 1: Copy all NON-transformer keys verbatim
    #         (CNN stem, final classifier, etc.)
    # ------------------------------------------------------------------
    transformer_key_prefixes = set()
    for pfx in layer_prefixes:
        transformer_key_prefixes.add(pfx)

    for key, value in old_model_state.items():
        # Skip keys that belong to a replaced transformer layer
        belongs_to_replaced = False
        for pfx in transformer_key_prefixes:
            if key.startswith(pfx + "."):
                belongs_to_replaced = True
                break
        if not belongs_to_replaced and key in new_state:
            new_state[key] = value

    # ------------------------------------------------------------------
    # Step 2: Transfer transformer-block weights with key remapping
    # ------------------------------------------------------------------
    for pfx in layer_prefixes:
        # 2a. Simple 1:1 renamed keys
        weight_map = build_weight_map(pfx, pfx)
        for old_key, new_key in weight_map.items():
            if old_key in old_model_state and new_key in new_state:
                new_state[new_key] = old_model_state[old_key]
            else:
                print(f"  [WARN] missing key pair: {old_key} -> {new_key}")

        # 2b. Fused QKV
        fuse_qkv_weights(old_model_state, pfx, new_state, pfx)

    # ------------------------------------------------------------------
    # Step 3: Load the assembled state dict (strict=False because I-ViT
    #         adds buffers like fc_scaling_factor that have no counterpart
    #         in the original model).
    # ------------------------------------------------------------------
    missing, unexpected = new_model.load_state_dict(new_state, strict=False)

    # Filter noise: quantisation buffers are expected to be "missing"
    # from the old model — they will be initialised on the first forward.
    real_missing = [k for k in missing
                    if not any(tok in k for tok in
                               ("scaling_factor", "weight_integer",
                                "bias_integer", "min_val", "max_val",
                                "act_scaling_factor", "norm_scaling_factor"))]
    if real_missing:
        print(f"  [WARN] Truly missing keys after weight transfer:\n    "
              + "\n    ".join(real_missing))

    return new_model


