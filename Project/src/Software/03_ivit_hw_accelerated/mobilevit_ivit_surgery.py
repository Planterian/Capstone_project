# 2. Integer-only MLP (replaces MobileViTIntermediate + MobileViTOutput)
# ===================================================================

class IViTMlp(nn.Module):
    """
    Two-layer MLP with ShiftGELU activation, mirroring the combined
    effect of HF's `MobileViTIntermediate` (fc1 + act) and
    `MobileViTOutput` (fc2 + dropout + residual-add).

    NOTE: The residual addition is handled *outside* this module
    (in the parent IViTMobileViTTransformerLayer) to match HF's
    data-flow exactly.
    """

    def __init__(self, hidden_size: int, intermediate_size: int,
                 drop: float = 0.0):
        super().__init__()
        # fc1: hidden -> intermediate   (was MobileViTIntermediate.dense)
        self.fc1 = QuantLinear(hidden_size, intermediate_size)
        self.act = IntGELU()       # ShiftGELU
        self.qact_gelu = QuantAct()
        self.qact1 = QuantAct()

        # fc2: intermediate -> hidden   (was MobileViTOutput.dense)
        self.fc2 = QuantLinear(intermediate_size, hidden_size)
        self.qact2 = QuantAct(16)

        self.drop = nn.Dropout(drop)

    def forward(self, x: torch.Tensor, act_scaling_factor: torch.Tensor):
        x, act_scaling_factor = self.fc1(x, act_scaling_factor)
        x, act_scaling_factor = self.qact_gelu(x, act_scaling_factor)
        x, act_scaling_factor = self.act(x, act_scaling_factor)
        x, act_scaling_factor = self.qact1(x, act_scaling_factor)
        x = self.drop(x)
        x, act_scaling_factor = self.fc2(x, act_scaling_factor)
        x, act_scaling_factor = self.qact2(x, act_scaling_factor)
        x = self.drop(x)
        return x, act_scaling_factor


